CREATE TABLE mining_schedule (
 schedule_id BIGINT AUTO_INCREMENT PRIMARY KEY,
 store_id INT NOT NULL,
 created_by INT NOT NULL,
 updated_by INT NOT NULL,
 frequency VARCHAR(10) NOT NULL,
 day_of_week INT NULL,
 day_of_month INT NULL,
 local_time VARCHAR(8) NOT NULL,
 time_zone VARCHAR(100) NOT NULL,
 lookback_days INT NOT NULL,
 compare_algorithms BOOLEAN NOT NULL DEFAULT FALSE,
 enabled BOOLEAN NOT NULL DEFAULT FALSE,
 next_fire_at TIMESTAMP NULL,
 schedule_version BIGINT NOT NULL DEFAULT 1,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_schedule_store_id UNIQUE(store_id,schedule_id),
 CONSTRAINT fk_schedule_store FOREIGN KEY(store_id) REFERENCES store(store_id),
 CONSTRAINT fk_schedule_creator FOREIGN KEY(created_by) REFERENCES app_user(user_id),
 CONSTRAINT fk_schedule_updater FOREIGN KEY(updated_by) REFERENCES app_user(user_id),
 CONSTRAINT ck_schedule_frequency CHECK(frequency IN ('WEEKLY','MONTHLY')),
 CONSTRAINT ck_schedule_day CHECK((frequency='WEEKLY' AND day_of_week IS NOT NULL AND day_of_week BETWEEN 1 AND 7 AND day_of_month IS NULL) OR (frequency='MONTHLY' AND day_of_month IS NOT NULL AND day_of_month BETWEEN 1 AND 31 AND day_of_week IS NULL)),
 CONSTRAINT ck_schedule_lookback CHECK(lookback_days BETWEEN 1 AND 3660),
 CONSTRAINT ck_schedule_version CHECK(schedule_version>0)
);
CREATE INDEX ix_mining_schedule_due ON mining_schedule(enabled,next_fire_at);
CREATE TABLE mining_schedule_occurrence (
 occurrence_id BIGINT AUTO_INCREMENT PRIMARY KEY,
 schedule_id BIGINT NOT NULL,
 store_id INT NOT NULL,
 scheduled_at TIMESTAMP NOT NULL,
 schedule_version BIGINT NOT NULL,
 config_version BIGINT NOT NULL,
 request_key VARCHAR(36) NOT NULL,
 snapshot_id INT NULL,
 request_id BIGINT NULL,
 status VARCHAR(20) NOT NULL,
 failure_code VARCHAR(40) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_schedule_occurrence UNIQUE(schedule_id,scheduled_at),
 CONSTRAINT uq_schedule_request_key UNIQUE(store_id,request_key),
 CONSTRAINT fk_occurrence_schedule FOREIGN KEY(store_id,schedule_id) REFERENCES mining_schedule(store_id,schedule_id),
 CONSTRAINT fk_occurrence_config FOREIGN KEY(config_version) REFERENCES mining_config_version(config_version),
 CONSTRAINT fk_occurrence_snapshot FOREIGN KEY(store_id,snapshot_id) REFERENCES utility_snapshot(store_id,snapshot_id),
 CONSTRAINT fk_occurrence_request FOREIGN KEY(store_id,request_id) REFERENCES mining_request(store_id,request_id),
 CONSTRAINT ck_occurrence_status CHECK(status IN ('PENDING','PROCESSING','DISPATCHED','COMPLETED','FAILED'))
);
