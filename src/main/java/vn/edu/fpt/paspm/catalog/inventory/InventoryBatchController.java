package vn.edu.fpt.paspm.catalog.inventory;

import java.util.List;

import jakarta.validation.Valid;
import jakarta.validation.constraints.Min;
import org.springframework.http.HttpStatus;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.security.core.annotation.AuthenticationPrincipal;
import org.springframework.security.oauth2.jwt.Jwt;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.PatchMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;
import org.springframework.web.bind.annotation.ResponseStatus;

import io.swagger.v3.oas.annotations.Operation;
import vn.edu.fpt.paspm.catalog.CatalogContracts.BatchCreateRequest;
import vn.edu.fpt.paspm.catalog.CatalogContracts.BatchPatchRequest;
import vn.edu.fpt.paspm.catalog.CatalogContracts.BatchView;

@RestController
@PreAuthorize("hasRole('STORE_ADMIN')")
public class InventoryBatchController {
    private final InventoryBatchService batches;
    private final InventorySummaryService summaries;

    public InventoryBatchController(InventoryBatchService batches, InventorySummaryService summaries) {
        this.batches = batches; this.summaries = summaries;
    }

    @Operation(operationId = "listProductBatches", summary = "List inventory batches for a Store product",
            description = "STORE_ADMIN only. Every batch carries the computed effectiveStatus (ACTIVE|BLOCKED|EXPIRED), daysToExpiry and warnings; the client never compares dates itself.")
    @GetMapping("/api/products/{id}/batches")
    public List<BatchView> list(@AuthenticationPrincipal Jwt jwt, @PathVariable("id") int productId) {
        return batches.list(jwt, productId);
    }

    @Operation(operationId = "createProductBatch", summary = "Receive an inventory batch for a Store product",
            description = "STORE_ADMIN only. Batch ID and batchCode are generated by the backend; do not send batchCode. It uses receivedAt's Store-local date and the next Product-scoped sequence (minimum three digits). Expiry date is required when the product requires expiry; pushDay must not be after expiryDate. pushDay is optional and is never auto-filled; the response warns with MISSING_PUSH_DAY when an expiry-tracked product's batch has none.")
    @PostMapping("/api/products/{id}/batches")
    @ResponseStatus(HttpStatus.CREATED)
    public BatchView create(@AuthenticationPrincipal Jwt jwt, @PathVariable("id") int productId,
                            @Valid @RequestBody BatchCreateRequest request) {
        return batches.create(jwt, productId, request);
    }

    @Operation(operationId = "getInventoryBatch", summary = "Get a Store inventory batch", description = "STORE_ADMIN only; foreign Store batches and batches of a soft-deleted product return 404.")
    @GetMapping("/api/inventory-batches/{id}")
    public BatchView get(@AuthenticationPrincipal Jwt jwt, @PathVariable int id) { return batches.get(jwt, id); }

    @Operation(operationId = "updateInventoryBatch", summary = "Update remaining quantity, block state and/or expiry date for a Store inventory batch",
            description = "STORE_ADMIN only. remainingQuantity must be 0..initialQuantity. batchCode, receivedAt and initialQuantity are immutable. Expiry date null/omitted is unchanged; DELETE /api/inventory-batches/{id}/expiry-date clears it when the product does not require expiry. pushDay must not be after expiryDate. An expired batch can still be edited; status accepts only ACTIVE|BLOCKED (EXPIRED is derived, never writable).")
    @PatchMapping("/api/inventory-batches/{id}")
    public BatchView update(@AuthenticationPrincipal Jwt jwt, @PathVariable int id,
                            @Valid @RequestBody BatchPatchRequest request) {
        return batches.update(jwt, id, request);
    }

    @Operation(summary = "Clear the expiry date for a Store inventory batch",
            description = "STORE_ADMIN only. Only allowed when the owning product does not require expiry. Idempotent.")
    @DeleteMapping("/api/inventory-batches/{id}/expiry-date")
    public BatchView clearExpiryDate(@AuthenticationPrincipal Jwt jwt, @PathVariable int id) {
        return batches.clearExpiryDate(jwt, id);
    }

    @Operation(summary = "Clear the push day for a Store inventory batch",
            description = "STORE_ADMIN only. Idempotent. Returns the updated batch; PATCH absent/null pushDay keeps its existing value.")
    @DeleteMapping("/api/inventory-batches/{id}/push-day")
    public BatchView clearPushDay(@AuthenticationPrincipal Jwt jwt, @PathVariable int id) {
        return batches.clearPushDay(jwt, id);
    }

    @Operation(summary = "Summarize derived inventory for a Store product",
            description = "STORE_ADMIN only. A batch is expired only when the Store-local date (Asia/Ho_Chi_Minh) is after its expiry date, so a batch expiring today is still sellable. "
                    + "Buckets never overlap: expired (any stored status) / blocked (not expired) / sellable (ACTIVE, not expired). expiringSoonQuantity = sellable with 0 <= daysToExpiry <= expiringWithinDays. batchesMissingPushDay counts the MISSING_PUSH_DAY warnings.")
    @GetMapping("/api/products/{id}/inventory-summary")
    public vn.edu.fpt.paspm.catalog.CatalogContracts.InventorySummary summary(
            @AuthenticationPrincipal Jwt jwt, @PathVariable("id") int productId,
            @RequestParam(defaultValue = "7") @Min(0) int expiringWithinDays) {
        return summaries.summarize(jwt, productId, expiringWithinDays);
    }
}
