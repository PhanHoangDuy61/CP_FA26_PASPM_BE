package vn.edu.fpt.paspm.catalog.product;

import jakarta.validation.Valid;
import org.springframework.http.HttpStatus;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.security.core.annotation.AuthenticationPrincipal;
import org.springframework.security.oauth2.jwt.Jwt;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PatchMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.ResponseStatus;
import org.springframework.web.bind.annotation.RestController;

import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import vn.edu.fpt.paspm.catalog.CatalogContracts.ProductPage;
import vn.edu.fpt.paspm.catalog.CatalogContracts.ProductRequest;
import vn.edu.fpt.paspm.catalog.CatalogContracts.ProductView;
import vn.edu.fpt.paspm.catalog.CatalogContracts.StatusRequest;

@RestController
@PreAuthorize("hasRole('STORE_ADMIN')")
public class ProductController {
    private final ProductService products;

    public ProductController(ProductService products) { this.products = products; }

    @Operation(operationId = "listProducts", summary = "Search and filter products in the authenticated Store",
            description = "STORE_ADMIN or MERCHANDISER. sortBy supports name, sku, category, unit, costPrice, sellingPrice, status, requiresExpiry and stockQuantity; equal values are ordered by product ID.")
    @GetMapping("/api/products")
    @PreAuthorize("hasAnyRole('STORE_ADMIN','MERCHANDISER')")
    public ProductPage list(@AuthenticationPrincipal Jwt jwt,
            @RequestParam(defaultValue = "") String search,
            @RequestParam(required = false) Integer categoryId,
            @RequestParam(defaultValue = "") String status,
            @RequestParam(defaultValue = "0") int page,
            @RequestParam(defaultValue = "20") int pageSize,
            @Parameter(schema = @Schema(allowableValues = {"name", "sku", "category", "unit", "costPrice",
                    "sellingPrice", "status", "requiresExpiry", "stockQuantity"}))
            @RequestParam(defaultValue = "name") String sortBy,
            @Parameter(schema = @Schema(allowableValues = {"asc", "desc"}))
            @RequestParam(defaultValue = "asc") String sortDirection) {
        return products.list(jwt, search, categoryId, status, page, pageSize, sortBy, sortDirection);
    }

    @Operation(operationId = "getProduct", summary = "Get a product and batch-derived stock for the authenticated Store",
            description = "STORE_ADMIN or MERCHANDISER.")
    @GetMapping("/api/products/{id}")
    @PreAuthorize("hasAnyRole('STORE_ADMIN','MERCHANDISER')")
    public ProductView get(@AuthenticationPrincipal Jwt jwt, @PathVariable int id) { return products.get(jwt, id); }

    @Operation(operationId = "createProduct", summary = "Create a product in the authenticated Store; stock is managed through batches",
            description = "STORE_ADMIN. Product ID and SKU are generated by the backend. A similar name returns 409 with code PRODUCT_NAME_CONFIRMATION_REQUIRED; retry with confirmSimilarName=true after user confirmation.")
    @ApiResponse(responseCode = "409",
            description = "Name warning: {code: PRODUCT_NAME_CONFIRMATION_REQUIRED, error, confirmWith: confirmSimilarName=true}; no write occurs until confirmed.")
    @PostMapping("/api/products")
    @ResponseStatus(HttpStatus.CREATED)
    public ProductView create(@AuthenticationPrincipal Jwt jwt, @Valid @RequestBody ProductRequest request) {
        return products.create(jwt, request);
    }

    @Operation(operationId = "updateProduct", summary = "Update product information without changing stock",
            description = "STORE_ADMIN. SKU is generated at create time and remains unchanged. A similar name in this Store returns 409 with code PRODUCT_NAME_CONFIRMATION_REQUIRED; retry with confirmSimilarName=true after user confirmation. Existing batches without expiry prevent enabling requiresExpiry.")
    @ApiResponse(responseCode = "409",
            description = "Name warning: {code: PRODUCT_NAME_CONFIRMATION_REQUIRED, error, confirmWith: confirmSimilarName=true}; no write occurs until confirmed.")
    @PutMapping("/api/products/{id}")
    public ProductView update(@AuthenticationPrincipal Jwt jwt, @PathVariable int id,
                              @Valid @RequestBody ProductRequest request) {
        return products.update(jwt, id, request);
    }

    @Operation(operationId = "deleteProduct", summary = "Soft-delete a product of the authenticated Store",
            description = "STORE_ADMIN of the owning Store only (another Store's, unknown or already deleted product is 404). "
                    + "409 with {code, error, reason, sellableQuantity, campaigns}: PRODUCT_HAS_SELLABLE_STOCK while ACTIVE, non-expired batches still hold units "
                    + "(a batch expiring today counts), PRODUCT_IN_LIVE_CAMPAIGN while a PUBLISHED or ACTIVE campaign layout (A or B) places the product; "
                    + "the stock code wins when both apply and campaigns is always listed. On success the row is kept (history, snapshots, mining, layouts, SKU), "
                    + "status becomes INACTIVE and the product disappears from catalogue reads before pagination. There is no restore; the SKU is never reused.")
    @ApiResponse(responseCode = "204", description = "Soft-deleted")
    @ApiResponse(responseCode = "409",
            description = "{code: PRODUCT_HAS_SELLABLE_STOCK | PRODUCT_IN_LIVE_CAMPAIGN, error, reason, sellableQuantity, campaigns:[{campaignId,status}]}")
    @DeleteMapping("/api/products/{id}")
    @ResponseStatus(HttpStatus.NO_CONTENT)
    public void delete(@AuthenticationPrincipal Jwt jwt, @PathVariable int id) { products.delete(jwt, id); }

    @Operation(summary = "Activate or deactivate a product", description = "STORE_ADMIN. A soft-deleted product is 404.")
    @PatchMapping("/api/products/{id}/status")
    public ProductView updateStatus(@AuthenticationPrincipal Jwt jwt, @PathVariable int id,
                                    @Valid @RequestBody StatusRequest request) {
        return products.updateStatus(jwt, id, request.status());
    }
}
